import { readFileSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'
import { format } from 'prettier'
import { globSync } from 'tinyglobby'
import { root } from './utils'

interface MappedFunction {
  name: string
  file: string
  pkg: string
}

const RE_EXPORT = /export\s+(?:async\s+)?function\s+(\w+)|export\s+const\s+(\w+)\s*=/g

function parseExports(file: string): string[] {
  const content = readFileSync(file, 'utf-8')
  const names: string[] = []
  for (const match of content.matchAll(RE_EXPORT)) {
    names.push(match[1] || match[2])
  }
  return names
}

/**
 * Scan every package `src` dir and regenerate `meta/functions.md` and
 * `meta/functions.ts` (the structured registry consumed by the docs
 * markdown transformer and the PWA route list), mirroring VueUse's
 * metadata-driven function list.
 */
export async function generateFunctionsMD() {
  const functions = collectFunctions()

  functions.sort((a, b) => a.name.localeCompare(b.name))

  const rows = functions.map((fn) => {
    const upstream = `source/vueuse/packages/${fn.pkg}/${fn.name}`
    const upstreamExists = globSync(`${upstream}/index.ts`, { cwd: root }).length > 0
    const upstreamRef = upstreamExists ? `packages/${fn.pkg}/${fn.name}` : '—'
    const status = upstreamExists ? '✅ ported' : '🚧 ported (no upstream match)'
    return `| \`${fn.name}\` | ${upstreamRef} | \`${fn.file}\` | ${status} |`
  })

  const md = `# Function mapping status

> Auto-generated by \`npm run update\` (scripts/update.ts) — do not edit by hand.
> The upstream source of truth is the \`source/vueuse\` submodule.

| VueUse function | source (vueuse) | reaxuse | status |
|---|---|---|---|
${rows.join('\n') || '| — | — | — | no hooks mapped yet |'}
`

  writeFileSync(join(root, 'meta/functions.md'), await format(md, { parser: 'markdown' }))
  console.log(`[update] wrote meta/functions.md (${functions.length} functions)`)
}

function collectFunctions(): MappedFunction[] {
  const files = globSync('packages/*/src/*.ts', {
    cwd: root,
    absolute: true,
  }).filter(file => !file.endsWith('index.ts') && !file.includes('.test.'))

  const functions: MappedFunction[] = []
  for (const file of files) {
    const rel = file.replace(/\\/g, '/')
    const [, pkg, basename] = rel.match(/packages\/(\w+)\/src\/(\w+)\.ts$/) || []
    if (!pkg || !basename)
      continue
    for (const name of parseExports(file)) {
      functions.push({ name, file: `packages/${pkg}/src/${basename}.ts`, pkg })
    }
  }
  return functions.sort((a, b) => a.name.localeCompare(b.name))
}

/**
 * Write `packages/metadata/src/functions.ts` — the structured function
 * registry (name/pkg/file) consumed by the docs markdown transformer and
 * the PWA route list. Mirrors VueUse's generated `packages/metadata/metadata.ts`.
 */
async function generateFunctionsTS() {
  const functions = collectFunctions()
  const ts = `/**
 * Function registry — auto-generated by \`npm run update\` (scripts/update.ts).
 * Do not edit by hand. Mirrors VueUse's generated
 * \`packages/metadata/metadata.ts\` (react-adapted).
 */
export interface FunctionInfo {
  name: string
  pkg: string
  file: string
}

export const functions: FunctionInfo[] = ${JSON.stringify(functions, null, 2)}
`
  writeFileSync(join(root, 'packages/metadata/src/functions.ts'), await format(ts, { parser: 'typescript', singleQuote: true, semi: false, trailingComma: 'all', printWidth: 120 }))
  console.log(`[update] wrote packages/metadata/src/functions.ts (${functions.length} functions)`)
}

/**
 * Regenerate `packages/functions.md` — the /functions/ docs page.
 * Mirrors VueUse's auto-generated `packages/functions.md`.
 */
async function generateFunctionsPage() {
  const functions = collectFunctions()
  // Link to the docs page derived from the implementation file's basename:
  // hooks are 1 file = 1 page named after the function (basename === name),
  // while grouped helpers share their group page (e.g. utils.ts → /shared/utils/index).
  const rows = functions.map(fn => `- [\`${fn.name}\`](/${fn.pkg}/${basename(fn.file, '.ts')}/index) — \`@reaxuse/${fn.pkg}\``)

  const md = `# Functions

The function list is generated by \`npm run update\` (scripts/update.ts) from
\`packages/*/src\`, mirroring VueUse's metadata-driven \`packages/functions.md\`.

> 🚧 The remaining ~200 \`@vueuse/core\` functions are being AI-mapped (in progress).
> Out of scope for now: \`router\` / \`rxjs\` / \`electron\` / \`nuxt\` / \`firebase\` sub-packages.

## Ported

${rows.join('\n') || '- none yet'}
`
  writeFileSync(join(root, 'packages/functions.md'), await format(md, { parser: 'markdown' }))
  console.log(`[update] wrote packages/functions.md (${functions.length} functions)`)
}

async function main() {
  await generateFunctionsMD()
  await generateFunctionsTS()
  await generateFunctionsPage()
}

main()
